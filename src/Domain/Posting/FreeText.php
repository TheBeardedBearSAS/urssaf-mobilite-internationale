namespace TheBeardedBear\UrssafMobiliteInternationale\Domain\Posting;

/**
 * Free text without any published limit ("commentaire", "natureAutre"): not validated (ADR 0008). Kept verbatim and
 * treated as personal data (it may name anyone).
 */
final readonly class FreeText
{
    use PersonalData;

    private function __construct(private string $value) {}

    public static function fromString(string $value): self
    {
        return new self($value);
    }

    public function value(): string
    {
        return $this->value;
    }

    public function equals(self $other): bool
    {
        return $this->value === $other->value;
    }
}
